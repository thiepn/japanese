import {test,expect} from "@playwright/test";
test("CUR-05 scope changes update original vocabulary and retain global due count",async({page})=>{
 await page.goto("./#course/A1");
 const panel=page.getByRole("region",{name:"Vocabulary and level reviews"});
 await expect(panel).toBeVisible();
 await expect(panel.getByText("due across Japanese")).toBeVisible();
 const global=await panel.locator(".cur05-global strong").innerText();
 await panel.getByRole("button",{name:"All levels",exact:true}).click();
 await expect(panel.getByRole("button",{name:"All levels",exact:true})).toHaveAttribute("aria-pressed","true");
 await expect(panel.locator(".cur05-global strong")).toHaveText(global);
 await panel.getByRole("button",{name:"Choose levels"}).click();
 await panel.getByLabel("A1",{exact:true}).check();
 await panel.getByLabel("B1",{exact:true}).check();
 await panel.getByLabel("Unassigned").check();
 await expect(panel.getByRole("button",{name:"Choose levels"})).toHaveAttribute("aria-pressed","true");
 await expect(panel.locator(".cur05-global strong")).toHaveText(global);
 await expect(panel.getByRole("heading",{name:"Source-linked vocabulary",exact:true})).toBeVisible();
 const sample=panel.locator(".cur05-vocabulary li").first();
 await expect(sample).toBeVisible();
 await sample.getByRole("button",{name:/^Preview /}).click();
 await expect(page.locator(".study-lesson")).toBeVisible();
 await page.getByRole("button",{name:"Exit"}).click();
 await expect(panel).toBeVisible();
});
test("CUR-05 source-owned per-unit links and planned C2 remain independently selectable",async({page})=>{
 await page.goto("./#course/A1");
 const catalog=page.getByRole("region",{name:"Six-level course catalog"});
 const panel=catalog.getByRole("region",{name:"Vocabulary and level reviews"});
 await expect(panel).toBeVisible();
 const unitLink=panel.locator(".cur05-links button").first();
 await expect(unitLink).toBeVisible();
 await unitLink.click();
 await expect(catalog.locator(".cur01-lessons li.cur01-active")).toHaveCount(1);
 await catalog.getByRole("tab",{name:/C2/}).click();
 await expect(catalog.getByText(/no published course units at this level/i)).toBeVisible();
 await expect(panel.getByRole("button",{name:"All levels",exact:true})).toBeVisible();
 await panel.getByRole("button",{name:"All levels",exact:true}).click();
 await expect(panel.locator(".cur05-vocabulary li").first()).toBeVisible();
});