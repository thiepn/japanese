import {test,expect} from "@playwright/test";
test("CUR-07 learner chooses two original unit Can-dos and resumes the same bounded comparison",async({page})=>{
 await page.goto("./#course/A1");
 const panel=page.getByRole("region",{name:"Vocabulary and level reviews"});
 await panel.getByRole("button",{name:"All levels",exact:true}).click();
 const row=panel.locator(".cur05-vocabulary li").filter({has:page.getByRole("button",{name:/Compare original source units/})}).first();
 await expect(row).toBeVisible();
 await row.getByRole("button",{name:/Compare original source units/}).click();
 const cmp=row.getByRole("region",{name:/Compare unit contexts/});
 await expect(cmp).toBeVisible();
 const first=cmp.getByRole("combobox",{name:"First source unit"});
 const second=cmp.getByRole("combobox",{name:"Contrasting source unit"});
 const firstValue=await first.inputValue();
 const secondValue=await second.inputValue();
 expect(firstValue).not.toBe(secondValue);
 const originalOptions=await second.locator("option").allTextContents();
 expect(originalOptions.length).toBeGreaterThanOrEqual(1);
 await cmp.getByRole("button",{name:"Practice comparison"}).click();
 await expect(page.locator(".study-lesson h1")).toBeVisible();
 await page.getByRole("button",{name:"Continue",exact:true}).click();
 const saved=await page.locator(".study-lesson h1").innerText();
 await page.getByRole("button",{name:"Exit"}).click();
 await expect(cmp.getByRole("button",{name:"Resume comparison"})).toBeVisible();
 await page.reload();
 const panel2=page.getByRole("region",{name:"Vocabulary and level reviews"});
 await panel2.getByRole("button",{name:"All levels",exact:true}).click();
 const row2=panel2.locator(".cur05-vocabulary li").filter({has:page.getByRole("button",{name:/Compare original source units/})}).first();
 await row2.getByRole("button",{name:/Compare original source units/}).click();
 const cmp2=row2.getByRole("region",{name:/Compare unit contexts/});
 await cmp2.getByRole("button",{name:"Resume comparison"}).click();
 await expect(page.locator(".study-lesson h1")).toHaveText(saved);
 await page.getByRole("button",{name:"Exit"}).click();
 await cmp2.getByRole("button",{name:"Restart comparison"}).click();
 await expect(page.locator(".study-lesson h1")).not.toHaveText(saved);
 await page.getByRole("button",{name:"Exit"}).click();
});
test("CUR-07 retains complete independent source exploration and original level filters",async({page})=>{
 await page.goto("./#course/A1");
 const panel=page.getByRole("region",{name:"Vocabulary and level reviews"});
 await panel.getByRole("button",{name:"Choose levels"}).click();
 await panel.getByRole("checkbox",{name:"A1"}).check();
 await panel.getByRole("checkbox",{name:"B1"}).check();
 await panel.getByRole("button",{name:"All levels",exact:true}).click();
 const row=panel.locator(".cur05-vocabulary li").filter({has:page.getByRole("button",{name:/Compare original source units/})}).first();
 await expect(row).toBeVisible();
 await row.getByRole("button",{name:/Explore original contexts/}).click();
 await expect(page.locator(".study-lesson")).toBeVisible();
 await page.getByRole("button",{name:"Exit"}).click();
 await expect(panel.getByRole("button",{name:"This level (A1)"})).toHaveAttribute("aria-pressed","true");
 await panel.getByRole("button",{name:"All levels",exact:true}).click();
 await expect(panel.getByRole("button",{name:"All levels",exact:true})).toHaveAttribute("aria-pressed","true");
});